export function ensureSpriteStyles() {
  if (typeof document === 'undefined' || document.getElementById('dot-sprite-css')) return;
  const style = document.createElement('style');
  style.id = 'dot-sprite-css';
  style.textContent = SPRITE_CSS;
  document.head.appendChild(style);
}

export function randomSpriteLook() {
  const pick = (a) => a[Math.floor(Math.random() * a.length)];
  return {
    body: pick(BODIES), tone: pick(TONES),
    hat: Math.random() < 0.85 ? pick(SPRITE_ITEMS.hat.slice(1)) : 'none',
    glasses: Math.random() < 0.5 ? pick(SPRITE_ITEMS.glasses.slice(1)) : 'none',
    accessory: Math.random() < 0.6 ? pick(SPRITE_ITEMS.accessory.slice(1)) : 'none',
  };
}
